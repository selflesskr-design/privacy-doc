export const GUIDES_PATH = '/guides'
export const GUIDES_TITLE = '파일·문서 실용 가이드'

const pathOf = (guide) => `${GUIDES_PATH}/${guide.slug}`

/** Cards for the /guides list. Guides marked `listed: false` stay off it. */
export const guideCards = () =>
  GUIDES.filter((g) => g.listed !== false).map((g) => ({
    category: g.category,
    label: g.cardTitle,
    text: g.cardText,
    href: pathOf(g),
  }))

/** Routable page objects, in the shape src/content/pages.js expects. */
export const guidePages = () =>
  GUIDES.map((g) => ({
    path: pathOf(g),
    title: g.title,
    description: g.description,
    h1: g.h1,
    breadcrumb: [
      { name: '홈', path: '/' },
      { name: GUIDES_TITLE, path: GUIDES_PATH },
    ],
    schema: 'Article',
    sections: g.sections,
  }))
